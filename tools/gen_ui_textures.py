#!/usr/bin/env python3
"""Generate textures/ui/plates.png and textures/ui/hardware.png — the 9-slice
frames Solar's UI is built from (docs/ui-style.md, "flight hardware").

plates.png (768 × 256): plate (screws), plateBare and screen at 256 px, the
same edge art as the small cells below plus a soft worn-enamel surface in the
middle (see `surface`). The panels, the HUD card and the CRT displays use it.
hardware.png (128 × 64): the 32-px cells below, flat in the middle, for keys,
rows, chips and wells (its plate, lamp and screen cells are kept for small
elements but unused by the shipped styles).

Every panel, key and readout window in the game is a FLAT ENAMEL FILL (with the
engine's grain, ui/solar.uistyle.ron) inside one of these frames. A frame is a
style's `frame:`; the engine draws it over the fill and multiplies it by the
style's `border_color`, so the art here is drawn in two inks only:

  * white at some alpha — a lit edge, a screw head, glass glare. The style's
    `border_color` colours it (warm bezel paint, a lit orange rim on hover);
  * black at some alpha — a cut edge, a shadowed lip, a screw slot. Black
    times any tint stays black, so the depth survives every tint.

The centre of every cell is transparent: the fill shows through, so a panel can
be any size without its surface stretching (only the 1–2 px edges stretch).

Pixel art, one texel per design unit at 720p: the UI is laid out at 720 lines
(MatchHeight), so at 720p a corner is drawn texel for texel. The engine's UI
sampler is linear, so at 1080p (×1.5) the edges soften slightly — see
docs/ui-style.md, "engine gaps".

Cells (32 × 32 px each, uv in the 128 × 64 atlas; slice = corner / 32):

    plate      (0,0)    raised enamel panel, four cross-head screws   corner 10
    plateBare  (32,0)   the same bevel without screws (cards, rows)   corner 6
    key        (64,0)   a raised keycap: lit top, thick dark lip      corner 6
    keyDown    (96,0)   the same key pressed in: shadow on top        corner 6
    well       (0,32)   a recessed CRT window: shadowed top, lit sill corner 6
    lamp       (32,32)  an annunciator lens: glare streak, dark rim   corner 6
    screen     (64,32)  a CRT display in its own enamel bezel          corner 8
    tag        (96,32)  a riveted placard: two rivets, square cut     corner 8

    python3 tools/gen_ui_textures.py

Deterministic: no randomness, no external inputs. Licence: generated by this
script for Solar, same licence as the project.
"""
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "textures" / "ui" / "hardware.png"
C = 32  # cell size

W = (1.0, 1.0, 1.0)
K = (0.0, 0.0, 0.0)


def cell():
    return np.zeros((C, C, 4), dtype=np.float32)


def put(a, x, y, rgb, alpha):
    """Composite one texel (straight alpha, 'over')."""
    if not (0 <= x < C and 0 <= y < C) or alpha <= 0:
        return
    src = np.array([*rgb, alpha], dtype=np.float32)
    dst = a[y, x]
    out_a = src[3] + dst[3] * (1 - src[3])
    if out_a <= 0:
        return
    rgb_out = (src[:3] * src[3] + dst[:3] * dst[3] * (1 - src[3])) / out_a
    a[y, x] = [*rgb_out, out_a]


def chamfer_mask(x, y, cut):
    """True outside a `cut`-px chamfer at each corner."""
    for cx, cy in ((x, y), (C - 1 - x, y), (x, C - 1 - y), (C - 1 - x, C - 1 - y)):
        if cx + cy < cut:
            return True
    return False


def ring(a, inset, cut, top, left, bottom, right):
    """One 1-px ring `inset` px in, each side its own (rgb, alpha)."""
    lo, hi = inset, C - 1 - inset
    for i in range(lo, hi + 1):
        for x, y, side in ((i, lo, top), (i, hi, bottom), (lo, i, left), (hi, i, right)):
            if not chamfer_mask(x, y, cut + inset * 0):
                put(a, x, y, *side)


def bevel(a, cut=2, lit=0.30, shade=0.50, outline=0.85, inner=0.07):
    """A raised edge: dark cut line, then a lit top/left and a shaded bottom/right."""
    ring(a, 0, cut, (K, outline), (K, outline), (K, outline), (K, outline))
    ring(a, 1, cut, (W, lit), (W, lit * 0.7), (K, shade), (K, shade * 0.8))
    ring(a, 2, cut, (W, inner), (W, inner * 0.6), (K, inner * 2), (K, inner * 1.5))


def screw(a, cx, cy):
    """A 5-px cross-head screw: lit dome, dark recess cross, a shadow below-right."""
    for dy in range(-3, 4):
        for dx in range(-3, 4):
            d2 = dx * dx + dy * dy
            if d2 <= 5:
                # dome: lit upper-left, darker lower-right
                shade = 0.55 - 0.10 * (dx + dy)
                put(a, cx + dx, cy + dy, W, max(0.15, min(0.85, shade)))
            elif d2 <= 9 and dx + dy > 0:
                put(a, cx + dx, cy + dy, K, 0.55)  # countersink shadow
            elif d2 <= 9:
                put(a, cx + dx, cy + dy, K, 0.30)
    for d in (-1, 0, 1):
        put(a, cx + d, cy, K, 0.80)
        put(a, cx, cy + d, K, 0.80)


def rivet(a, cx, cy):
    for dy in range(-3, 4):
        for dx in range(-3, 4):
            d2 = dx * dx + dy * dy
            if d2 <= 4:
                put(a, cx + dx, cy + dy, W, max(0.2, 0.62 - 0.12 * (dx + dy)))
            elif d2 <= 8 and dx + dy > 0:
                put(a, cx + dx, cy + dy, K, 0.5)


def plate(screws=True):
    a = cell()
    bevel(a, cut=2, lit=0.32, shade=0.55, outline=0.9)
    if screws:
        for cx, cy in ((5, 5), (C - 6, 5), (5, C - 6), (C - 6, C - 6)):
            screw(a, cx, cy)
    return a


def key(down=False):
    a = cell()
    ring(a, 0, 2, (K, 0.9), (K, 0.9), (K, 0.9), (K, 0.9))
    if not down:
        # raised: bright top edge, soft sides, a 2-px dark lip (the key's thickness)
        ring(a, 1, 2, (W, 0.42), (W, 0.22), (K, 0.65), (K, 0.35))
        ring(a, 2, 2, (W, 0.10), (W, 0.06), (K, 0.45), (K, 0.12))
    else:
        # pressed in: the top lip falls into shadow, the bottom catches light
        ring(a, 1, 2, (K, 0.60), (K, 0.40), (W, 0.16), (W, 0.08))
        ring(a, 2, 2, (K, 0.30), (K, 0.18), (W, 0.04), (W, 0.0))
    return a


def well():
    a = cell()
    # the hole's lit sill (bottom/right) and the bezel's shadow inside (top/left)
    ring(a, 0, 3, (K, 0.55), (K, 0.45), (W, 0.22), (W, 0.16))
    ring(a, 1, 3, (K, 0.85), (K, 0.80), (K, 0.80), (K, 0.80))
    ring(a, 2, 3, (K, 0.50), (K, 0.40), (K, 0.10), (K, 0.10))
    ring(a, 3, 3, (K, 0.22), (K, 0.16), (K, 0.0), (K, 0.0))
    return a


def lamp():
    a = cell()
    ring(a, 0, 2, (K, 0.9), (K, 0.9), (K, 0.9), (K, 0.9))
    ring(a, 1, 2, (W, 0.30), (W, 0.18), (K, 0.35), (K, 0.25))
    for i in range(3, C - 3):
        put(a, i, 3, W, 0.12)  # lens glare across the top
    return a


def screen():
    """A CRT display set in its own enamel bezel. The band is drawn OPAQUE in
    grey, so the style's bezel tint turns it into painted metal; inside it the
    lip drops into shadow onto the glass (the element's fill)."""
    a = cell()
    ring(a, 0, 2, (K, 0.9), (K, 0.9), (K, 0.9), (K, 0.9))
    ring(a, 1, 2, ((0.36,) * 3, 1), ((0.30,) * 3, 1), ((0.15,) * 3, 1), ((0.17,) * 3, 1))
    for i in (2, 3):
        ring(a, i, 2, ((0.22,) * 3, 1), ((0.21,) * 3, 1), ((0.19,) * 3, 1), ((0.20,) * 3, 1))
    ring(a, 4, 3, ((0.10,) * 3, 1), ((0.11,) * 3, 1), ((0.30,) * 3, 1), ((0.27,) * 3, 1))
    ring(a, 5, 4, (K, 0.85), (K, 0.80), (K, 0.55), (K, 0.55))
    ring(a, 6, 4, (K, 0.40), (K, 0.35), (K, 0.0), (K, 0.0))
    return a


def tag():
    a = cell()
    ring(a, 0, 0, (K, 0.85), (K, 0.85), (K, 0.85), (K, 0.85))
    ring(a, 1, 0, (W, 0.28), (W, 0.20), (K, 0.45), (K, 0.35))
    rivet(a, 4, 4)
    rivet(a, C - 5, 4)
    rivet(a, 4, C - 5)
    rivet(a, C - 5, C - 5)
    return a


# ── the big plates: the same edges, with a worn-enamel surface in the middle ──
#
# A panel's middle patch is stretched to the panel's size, so it can only
# carry LOW-FREQUENCY material: soft mottling of the paint (two octaves of
# blurred noise) and a few faint scuffs, at very low contrast. Sampled with the
# UI's linear filter it reads as enamel under light, never as pixels. The fine
# grain on top is the engine's per-pixel film grain (`grain`, scale 0.5 in
# ui/solar.uistyle.ron), which does not scale with the panel.
BIG = 256          # big cell size; its corners are still 1 texel per unit
EDGE = 12          # nothing in the middle comes nearer the edge than this


def blur(a, sigma):
    """Gaussian blur by FFT (periodic) — numpy only."""
    n = a.shape[0]
    f = np.fft.fftfreq(n)
    g = np.exp(-2 * (np.pi * sigma) ** 2 * (f[:, None] ** 2 + f[None, :] ** 2))
    return np.real(np.fft.ifft2(np.fft.fft2(a) * g))


def mottle(rng, n):
    """Signed soft mottling in -1..1: broad blotches + finer clouding."""
    m = 0.55 * blur(rng.standard_normal((n, n)), 12) + 0.45 * blur(rng.standard_normal((n, n)), 4)
    m /= np.abs(m).max() + 1e-6
    # A few soft scuffs: short light streaks, the paint rubbed thin.
    for _ in range(8):
        x0, y0 = rng.uniform(EDGE + 8, n - EDGE - 8, 2)
        ang, ln = rng.uniform(-0.5, 0.5), rng.uniform(10, 34)
        s = np.zeros((n, n))
        for k in np.linspace(0, 1, 40):
            xi, yi = int(x0 + np.cos(ang) * ln * k), int(y0 + np.sin(ang) * ln * k)
            if 0 <= xi < n and 0 <= yi < n:
                s[yi, xi] = 1.0
        m += 0.9 * blur(s, 1.4) / (blur(s, 1.4).max() + 1e-6) * rng.uniform(0.25, 0.5)
    return np.clip(m, -1, 1)


def surface(a, rng, base=0.035, amp=0.030):
    """Lay the mottling into the middle of a big cell, faded in from the edge.

    It is drawn in ONE ink, black, as a gently varying alpha around `base`:
    lighter patches are simply where less of it is. Two inks at very low
    alpha (the first try) left only three or four 8-bit alpha steps, which
    the linear filter drew as hard-edged camouflage; one ink over ~16 steps,
    dithered when written out (see `save`), stays a smooth cloud."""
    n = a.shape[0]
    m = mottle(rng, n)
    yy, xx = np.mgrid[0:n, 0:n]
    d = np.minimum.reduce([xx, yy, n - 1 - xx, n - 1 - yy]).astype(np.float32)
    fade = np.clip((d - EDGE) / 10.0, 0, 1)
    alpha = np.clip(base - amp * m, 0, 1) * fade
    for y in range(n):
        for x in range(n):
            if alpha[y, x] > 0:
                put(a, x, y, K, float(alpha[y, x]))


def save(img, path, dither_seed=None):
    """Write RGBA8; with a seed, the alpha is dithered by half a step so a
    faint gradient is not quantised into contours."""
    a = np.clip(img, 0, 1) * 255
    if dither_seed is not None:
        r = np.random.default_rng(dither_seed).uniform(-0.5, 0.5, a.shape[:2])
        a[..., 3] = np.where(a[..., 3] > 0, a[..., 3] + r, 0)
    Image.fromarray(np.clip(a + 0.5, 0, 255).astype(np.uint8), "RGBA").save(path)


def big(fn, seed, base=0.035, amp=0.030, **kw):
    """Run a 32-px cell builder at BIG size, then add the surface."""
    global C
    C = BIG
    try:
        a = fn(**kw)
        surface(a, np.random.default_rng(seed), base, amp)
    finally:
        C = 32
    return a


def main():
    # plates.png: plate (screws) | plateBare | screen, 256 px each
    plates = np.concatenate([big(plate, 11, screws=True), big(plate, 12, screws=False),
                             big(screen, 13, base=0.015, amp=0.012)], axis=1)
    out2 = OUT.parent / "plates.png"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    save(plates, out2, dither_seed=5)
    print("wrote", out2.relative_to(ROOT), plates.shape[1], "x", plates.shape[0])

    atlas = np.zeros((2 * C, 4 * C, 4), dtype=np.float32)
    cells = [[plate(True), plate(False), key(False), key(True)],
             [well(), lamp(), screen(), tag()]]
    for r, row in enumerate(cells):
        for c, img in enumerate(row):
            atlas[r * C:(r + 1) * C, c * C:(c + 1) * C] = img
    OUT.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray((np.clip(atlas, 0, 1) * 255 + 0.5).astype(np.uint8), "RGBA").save(OUT)
    print("wrote", OUT.relative_to(ROOT), atlas.shape[1], "x", atlas.shape[0])


if __name__ == "__main__":
    main()
