#!/usr/bin/env python3
"""Writes the rain's screen passes: shaders/rainFx.flsl (Medium), rainFxHigh.flsl
(High and Ultra) and rainWet.flsl (Low). scripts/rain_fx.lua drives them.

flsl has no loops or functions, so the per-layer, per-height work is unrolled
here. Edit this file, not the .flsl files, and run it:

    python3 tools/gen_rain_fx.py

WHAT THE PASS DRAWS, from the frame's depth (nothing is spawned, nothing is on
the CPU but a handful of uniforms a frame):

  * WET: every surface the rain reaches darkens (up-facing most, walls a
    little, overhangs not at all) and takes a sheen of the sky at grazing
    angles, as wet ground, a wet pad and a wet hull do.
  * PUDDLES: on flat ground, where a noise fixed in the PLANET's frame dips
    below a level that rises the longer it rains, a dark mirror of the sky.
  * RINGS: in the puddles, ripples spreading from where drops land.
  * SPLASHES: a crown of spray thrown up where each drop lands, on anything
    flat (ground, the pad, a hull, a helmet), near the camera. A splash stands
    UP from the surface: the ray is asked where it passes a few centimetres
    over the surface it hit, and a splash there covers that pixel, so the
    spray rises in front of the ground behind it and nothing needs drawing.

Drops land at random in cells of a grid on the ground (a tangent plane at an
anchor near the camera, fixed in the planet's frame: the planet moves metres a
tick and turns, and a pattern anchored in world space would slide). Each cell
fires once a cycle, with the rain rate as its chance; a few grids of other
sizes and periods overlaid hide the lattice.
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

# (cell size m, period s, offset) per grid: the shaders' DEFAULTS only. The
# drop field itself (these grids, the anchor frame, the rate) is DATA in
# scripts/rain_fx.lua (GRIDS), sent as uniforms every frame, so the placement
# lives apart from the drawing (a compute pass can take it over unchanged).
LAYERS = {
    "rainFx": [(0.45, 0.95, (0.0, 0.0)), (0.6, 1.27, (0.37, 0.71))],
    "rainFxHigh": [(0.42, 0.9, (0.0, 0.0)), (0.56, 1.13, (0.37, 0.71)), (0.73, 1.41, (0.13, 0.53))],
}
# heights (m) at which the spray is looked for over the surface
HEIGHTS = {
    "rainFx": [0.04],
    "rainFxHigh": [0.025, 0.07],
}

HEAD = """// {name} — GENERATED by tools/gen_rain_fx.py (edit that, not this).
// Rain on the ground, read from the frame's depth: wet surfaces, puddles that
// mirror the sky, ripples in them and the spray of drops landing near the
// camera. Driven by scripts/rain_fx.lua. {what}
shader {name} {{
  stage post
  // the anchor: a point on the ground near the camera, in WORLD space (fixed in
  // the planet's frame by the script, which re-sends it every frame)
  uniform anchor: vec3 = vec3(0.0, 0.0, 0.0)
  // the tangent plane at the anchor: east, north, up (world, unit)
  uniform axisE: vec3 = vec3(1.0, 0.0, 0.0)
  uniform axisN: vec3 = vec3(0.0, 0.0, 1.0)
  uniform axisU: vec3 = vec3(0.0, 1.0, 0.0)
  // the planet's own axes (world, unit) and the anchor in them (m): the
  // puddles are a noise in the planet's frame, so they stay put
  uniform planetX: vec3 = vec3(1.0, 0.0, 0.0)
  uniform planetY: vec3 = vec3(0.0, 1.0, 0.0)
  uniform planetZ: vec3 = vec3(0.0, 0.0, 1.0)
  uniform anchorLocal: vec3 = vec3(0.0, 0.0, 0.0)
  // x: drops landing (0..1), y: how wet (0..1), z: puddles (0..1), w: how far
  // out the splashes are drawn (m)
  uniform rain: vec4 = vec4(0.0, 0.0, 0.0, 20.0)
  // what a wet surface mirrors: the sky's colour at the horizon, in real light
  uniform sky: vec3 = vec3(0.5, 0.55, 0.6)
  // the light a drop is seen by
  uniform drop: vec3 = vec3(0.6, 0.65, 0.7)
  // the haze: x start, y end of the flat ramp (m), z the marched density (1/m)
  uniform fog: vec3 = vec3(100000.0, 200000.0, 0.0)
{grids}"""

COMMON = """
  let c0 = sceneColor().rgb
  let d = sceneDepth()
  let ray = sceneRay()
  let fwd = sceneRay(vec2(0.5, 0.5))
  let solid = 1.0 - step(50000.0, d)
  let cosf = max(dot(ray, fwd), 0.05)
  let dist = min(d / cosf, 60000.0)
  let q = cameraPosition() + ray * dist - anchor
  // the surface's normal in the world, from this pixel's point and its right
  // and lower neighbours' (cheaper than sceneNormal plus the camera's axes,
  // and the neighbours' spacing is the pixel's footprint on the surface). A
  // pixel on a silhouette (a neighbour much further or nearer) is left dry.
  let tx = screenTexel()
  let dX = sceneDepth(uv + vec2(tx.x, 0.0))
  let dY = sceneDepth(uv + vec2(0.0, tx.y))
  let rX = sceneRay(uv + vec2(tx.x, 0.0))
  let rY = sceneRay(uv + vec2(0.0, tx.y))
  let eX = rX * (dX / max(dot(rX, fwd), 0.05)) - ray * dist
  let eY = rY * (dY / max(dot(rY, fwd), 0.05)) - ray * dist
  let nw0 = normalize(cross(eX, eY))
  let nw = nw0 * sign(dot(nw0, ray) * -1.0 + 0.000001)
  let edge = step(abs(dX - d) + abs(dY - d), d * 0.08 + 0.05)
  let up = dot(nw, axisU) * edge
  let foot = max(length(eX), length(eY))
  // how much of the surface's own light the haze leaves (the pass runs on the
  // finished frame, so the far ground's wet look fades into the haze)
  let fogT = (1.0 - saturate((dist - fog.x) / max(fog.y - fog.x, 1.0))) * exp(-fog.z * dist) * solid
  // wet: up-facing surfaces most, walls a little, overhangs not at all
  let face = saturate(0.35 + 0.65 * up)
  let flatUp = smoothstep(0.8, 0.95, up)
  let wet = rain.y * face * fogT
  // the sky's sheen at grazing angles (Schlick)
  let cosv = saturate(dot(ray * -1.0, nw))
  // (capped: at a grazing angle a whole puddle went the sky's colour and read as snow)
  let fres = min(0.02 + 0.98 * pow(1.0 - cosv, 5.0), 0.45)
"""

PUDDLES = """
  // puddles: a noise in the planet's frame under a level that rises with the rain
  let L = vec3(dot(q, planetX), dot(q, planetY), dot(q, planetZ)) + anchorLocal
  let pn = valueNoise(L * 0.42) * 0.68 + valueNoise(vec2(L.x + L.y * 0.71, L.z - L.y * 0.63) * 1.9) * 0.32
  let lvl = 0.73 - 0.11 * rain.z
  let pud = smoothstep(lvl, lvl + 0.06, pn) * smoothstep(0.93, 0.985, up) * saturate(rain.z * 3.0) * fogT
"""

FOOT = """
  let dn = max(dot(ray, axisU) * -1.0, 0.12)
  let near = (1.0 - smoothstep(rain.w * 0.4, rain.w, dist)) * flatUp * solid
"""


def hash12(prefix, a):
    """Dave Hoskins' hash12 on vec2 expression `a`, no sin (large cells stay random)."""
    return f"""  let {prefix}a = fract(vec3({a}.x, {a}.y, {a}.x) * 0.1031)
  let {prefix}b = {prefix}a + dot({prefix}a, vec3({prefix}a.y, {prefix}a.z, {prefix}a.x) + 33.33)
  let {prefix} = fract(({prefix}b.x + {prefix}b.y) * {prefix}b.z)
"""


def cell(tag, gexpr, cs, per, ofs):
    """One grid's drop at point g (metres in the tangent plane): its cell, the
    drop's place in the cell, its phase in the cycle and whether it fell."""
    s = f"""  let g{tag} = {gexpr} + vec2({ofs[0]}, {ofs[1]})
  let k{tag} = floor(g{tag} / {cs})
  let f{tag} = g{tag} / {cs} - k{tag}
"""
    s += hash12(f"ha{tag}", f"k{tag}")
    s += hash12(f"hb{tag}", f"(k{tag} + vec2(19.19, 7.31))")
    s += f"""  let ph{tag} = time / {per} + ha{tag}
  let cy{tag} = floor(ph{tag})
  let t{tag} = ph{tag} - cy{tag}
"""
    s += hash12(f"hc{tag}", f"(k{tag} + vec2(cy{tag} * 3.17, cy{tag} * 1.73))")
    s += f"""  let on{tag} = step(hc{tag}, rain.x)
  // the drop sits in the middle half of its cell, so its ring never leaves it
  let r{tag} = length(f{tag} - vec2(0.25 + 0.5 * ha{tag}, 0.25 + 0.5 * hb{tag})) * {cs}
"""
    return s


def gen(name):
    layers, heights = LAYERS[name], HEIGHTS[name]
    grids = "".join(
        f"  // drop grid {i}: x cell size (m), y period (s), zw offset (m) — scripts/rain_fx.lua GRIDS\n"
        f"  uniform grid{i}: vec4 = vec4({cs}, {per}, {o[0]}, {o[1]})\n" for i, (cs, per, o) in enumerate(layers))
    out = [HEAD.format(name=name, grids=grids, what="Medium: two grids, spray looked for at one height."
                       if name == "rainFx" else "High and Ultra: three grids, spray at two heights.")]
    out.append(COMMON)
    out.append(PUDDLES)
    out.append(FOOT)
    out.append("  let gq = vec2(dot(q, axisE), dot(q, axisN))\n")
    rings, spray = [], []
    for i in range(len(layers)):
        cs, per, ofs = f"grid{i}.x", f"grid{i}.y", (f"grid{i}.z", f"grid{i}.w")
        rmax = f"({cs} * 0.25)"
        tag = f"{i}"
        out.append(f"  // ── grid {i}: cells grid{i}.x m across, a drop every grid{i}.y s at most ──\n")
        out.append(cell(tag, "gq", cs, per, ofs))
        # the ripple: a ring out to the cell's quarter, fading as it spreads
        out.append(f"""  let rr{tag} = {rmax} * sqrt(t{tag})
  let rw{tag} = max(0.008 + 0.01 * t{tag}, foot)
  let ring{tag} = exp(((r{tag} - rr{tag}) / rw{tag}) * ((r{tag} - rr{tag}) / rw{tag}) * -1.0) * (1.0 - t{tag}) * (1.0 - t{tag}) * on{tag} * min(0.012 / rw{tag}, 1.0)
""")
        out.append(f"""  let hit{tag} = exp(r{tag} * r{tag} / max(0.0001, foot * foot * 0.5 + 0.00006) * -1.0) * (1.0 - smoothstep(0.0, 0.03, t{tag})) * on{tag}
""")
        rings.append(f"ring{tag}")
        spray.append(f"hit{tag}")
        # the spray: in the first fifth of the cycle a crown rises and falls
        for j, h in enumerate(heights):
            tj = f"{i}{j}"
            out.append(f"""  let qh{tj} = q - ray * min({h:.3f} / dn, 0.8)
""")
            out.append(cell(tj, "vec2(dot(qh{0}, axisE), dot(qh{0}, axisN))".format(tj), cs, per, ofs))
            # the crown: 0..0.24 of the cycle. Seen at height h over the
            # surface it is a broken ring of droplets (spokes round the drop's
            # centre) that flares out as it rises and sinks back; the higher
            # it is looked for the thinner and fainter. Each drop has its own
            # size and brightness (hb), and the impact itself is a bright
            # point for the first instant.
            out.append(f"""  let ct{tj} = saturate(t{tj} / 0.24)
  let ch{tj} = (0.035 + 0.075 * hb{tj}) * sin(ct{tj} * 3.1416)
  let cr{tj} = (0.006 + (0.03 + 0.025 * hb{tj}) * ct{tj}) * (1.0 + {h:.3f} * 7.0)
  let cw{tj} = max(0.008 + 0.01 * ct{tj}, foot * 0.6)
  let cd{tj} = g{tj} - (k{tj} + vec2(0.25 + 0.5 * ha{tj}, 0.25 + 0.5 * hb{tj})) * {cs}
  let sp{tj} = pow(saturate(0.5 + 0.5 * sin(atan2(cd{tj}.y, cd{tj}.x) * 5.0 + ha{tj} * 40.0 + {h:.3f} * 30.0)), 2.0)
  let crown{tj} = exp(((r{tj} - cr{tj}) / cw{tj}) * ((r{tj} - cr{tj}) / cw{tj}) * -1.0) * mix(1.0, sp{tj}, 0.55 * min(0.012 / cw{tj}, 1.0)) * smoothstep(ch{tj}, ch{tj} * 0.5, {h:.3f}) * step(t{tj}, 0.24) * on{tj} * min(0.012 / cw{tj}, 1.0) * (0.45 + 0.55 * hb{tj})
""")
            spray.append(f"crown{tj}")
    out.append(f"  let rings = saturate({' + '.join(rings)})\n")
    out.append(f"  let spray = saturate({' + '.join(spray)})\n")
    out.append("""
  // ── the composite ──
  // wet darkens (the film of water stops the surface scattering its light) and
  // mirrors the sky at grazing angles; a puddle is darker and a clearer
  // mirror, broken up where the rings run across it
  let dark = 1.0 - wet * 0.25 - pud * 0.22
  let sheen = sky * fres * (wet * flatUp * 0.3 + wet * 0.1 + pud * (0.85 + rings * 1.6))
  let spr = drop * (spray * 0.75 + rings * pud * 0.2) * near * fogT
  output color = vec4(c0 * dark + sheen + spr, 1.0)
}
""")
    return "".join(out)


def gen_wet():
    out = [HEAD.format(name="rainWet", grids="", what="Low: wet surfaces and puddles only, no drops.")]
    out.append(COMMON)
    out.append(PUDDLES)
    out.append("""
  let dark = 1.0 - wet * 0.25 - pud * 0.22
  let sheen = sky * fres * (wet * flatUp * 0.3 + wet * 0.1 + pud * 0.85)
  output color = vec4(c0 * dark + sheen, 1.0)
}
""")
    return "".join(out)


if __name__ == "__main__":
    for n in ("rainFx", "rainFxHigh"):
        with open(os.path.join(ROOT, "shaders", n + ".flsl"), "w") as f:
            f.write(gen(n))
    with open(os.path.join(ROOT, "shaders", "rainWet.flsl"), "w") as f:
        f.write(gen_wet())
    print("wrote shaders/rainFx.flsl, rainFxHigh.flsl, rainWet.flsl")
